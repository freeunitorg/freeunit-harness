#!/usr/bin/env python3
"""Write the per-agent files from their sources, and the shared links.

Sources (edit these):
  AGENTS.md          instructions for every agent
  skills/<n>/        skills in the Agent Skills format
  agents/<n>.md      role briefs; frontmatter has name, description, and a
                     `claude:` and an `opencode:` block for each tool
  recipes/<n>.md     task recipes; an `opencode:` block makes an OpenCode command

Outputs (never edit these):
  CLAUDE.md -> AGENTS.md
  .agents/skills -> ../skills       Codex, agy, dsh, Pi, Kilo, Cursor, OpenCode
  .claude/skills -> ../skills       Claude Code
  .claude/agents/<n>.md             from agents/<n>.md
  .opencode/agents/<n>.md           from agents/<n>.md
  .opencode/commands/<n>.md         from recipes/<n>.md

When `git config core.symlinks` is false, the links are written as copies.

Usage: tools/gen-agents.py [--root DIR] [--check]
  --check   change nothing; exit 1 and list each difference when the tree
            differs from a fresh run.
Exit: 0 done or clean, 1 differences found (--check), 2 bad source.
"""
import argparse
import filecmp
import os
import posixpath
import re
import shutil
import subprocess
import sys

MARK = "# Generated by tools/gen-agents.py from {src}. Do not edit; edit the source and run make agents."
MARK_RE = re.compile(r"^# Generated by tools/gen-agents\.py from ", re.M)
LINKS = (("CLAUDE.md", "AGENTS.md"), (".agents/skills", "../skills"), (".claude/skills", "../skills"))
OUT_DIRS = (".claude/agents", ".opencode/agents", ".opencode/commands")
LINK_RE = re.compile(r"(\]\()([^)\s]+)(\))")


class SourceError(Exception):
    pass


def parse(path):
    """Split a source into ({top-level key: raw lines}, body). Only a YAML subset is read:
    a top-level key starts at column 0; its value is the rest of that line plus the
    indented lines after it. Blocks are copied, not interpreted."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if not text.startswith("---\n"):
        raise SourceError(f"{path}: no frontmatter")
    end = text.find("\n---\n", 3)
    if end < 0:
        raise SourceError(f"{path}: frontmatter is not closed")
    keys, cur = {}, None
    for line in text[4:end].split("\n"):
        m = re.match(r"([A-Za-z_][\w-]*):(.*)$", line)
        if m:
            cur = m.group(1)
            if cur in keys:
                raise SourceError(f"{path}: duplicate key {cur}")
            keys[cur] = [line]
        elif cur and (line.startswith((" ", "\t")) or not line.strip()):
            keys[cur].append(line)
        else:
            raise SourceError(f"{path}: cannot read frontmatter line {line!r}")
    for k in ("name", "description"):
        if k not in keys:
            raise SourceError(f"{path}: frontmatter has no {k}")
    name = keys["name"][0].split(":", 1)[1].strip()
    stem = os.path.splitext(os.path.basename(path))[0]
    if name != stem:
        raise SourceError(f"{path}: name {name!r} is not the file name {stem!r}")
    return keys, text[end + 5:]


def block(keys, key):
    """The lines under `key:`, dedented by their common indent."""
    lines = [l for l in keys.get(key, [])[1:] if l.strip()]
    if not lines:
        return []
    ind = min(len(l) - len(l.lstrip()) for l in lines)
    return [l[ind:] for l in lines]


def relink(body, src_dir, out_dir):
    """Rewrite relative Markdown links so they point at the same file from out_dir."""
    def fix(m):
        target = m.group(2)
        if re.match(r"[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith(("#", "/")):
            return m.group(0)
        path, sep, frag = target.partition("#")
        new = posixpath.relpath(posixpath.normpath(posixpath.join(src_dir, path)), out_dir)
        return m.group(1) + new + sep + frag + m.group(3)
    return LINK_RE.sub(fix, body)


def render(src_rel, front, body, src_dir, out_dir):
    head = ["---", MARK.format(src=src_rel)] + front + ["---"]
    return "\n".join(head) + "\n" + relink(body, src_dir, out_dir)


def sources(root, sub):
    d = os.path.join(root, sub)
    if not os.path.isdir(d):
        return []
    return sorted(f for f in os.listdir(d) if f.endswith(".md") and f != "README.md")


def expected(root):
    """{output path relative to root: content} for every generated file."""
    out = {}
    for f in sources(root, "agents"):
        src = f"agents/{f}"
        keys, body = parse(os.path.join(root, src))
        desc = keys["description"]
        if "claude" in keys:
            out[f".claude/agents/{f}"] = render(src, keys["name"] + desc + block(keys, "claude"),
                                                body, "agents", ".claude/agents")
        if "opencode" in keys:
            out[f".opencode/agents/{f}"] = render(src, desc + block(keys, "opencode"),
                                                  body, "agents", ".opencode/agents")
    for f in sources(root, "recipes"):
        src = f"recipes/{f}"
        keys, body = parse(os.path.join(root, src))
        if "opencode" in keys:
            out[f".opencode/commands/{f}"] = render(src, keys["description"] + block(keys, "opencode"),
                                                    body, "recipes", ".opencode/commands")
    return out


def use_symlinks(root):
    r = subprocess.run(["git", "-C", root, "config", "--bool", "core.symlinks"],
                       capture_output=True, text=True)
    return r.stdout.strip() != "false"


def stale(root, want):
    """Generated files on disk that no source produces any more."""
    found = []
    for d in OUT_DIRS:
        p = os.path.join(root, d)
        if not os.path.isdir(p):
            continue
        for f in sorted(os.listdir(p)):
            rel = f"{d}/{f}"
            if rel in want or not f.endswith(".md"):
                continue
            with open(os.path.join(p, f), encoding="utf-8", errors="replace") as fh:
                if MARK_RE.search(fh.read(4096)):
                    found.append(rel)
    return found


def same_tree(a, b):
    if os.path.islink(b) or not os.path.isdir(b):
        return False
    c = filecmp.dircmp(a, b)
    if c.left_only or c.right_only or c.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, c.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(same_tree(os.path.join(a, s), os.path.join(b, s)) for s in c.common_dirs)


def link_ok(root, path, target, links):
    p = os.path.join(root, path)
    if links:
        return os.path.islink(p) and os.readlink(p) == target
    src = os.path.normpath(os.path.join(os.path.dirname(p), target))
    if os.path.isdir(src):
        return same_tree(src, p)
    return os.path.isfile(p) and not os.path.islink(p) and filecmp.cmp(src, p, shallow=False)


def remove(p):
    if os.path.islink(p) or os.path.isfile(p):
        os.unlink(p)
    elif os.path.isdir(p):
        shutil.rmtree(p)


def write_link(root, path, target, links):
    p = os.path.join(root, path)
    os.makedirs(os.path.dirname(p) or root, exist_ok=True)
    remove(p)
    if links:
        os.symlink(target, p)
        return
    src = os.path.normpath(os.path.join(os.path.dirname(p), target))
    if os.path.isdir(src):
        shutil.copytree(src, p, ignore=shutil.ignore_patterns("__pycache__"))
    else:
        shutil.copyfile(src, p)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the per-agent files and links from their sources.")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    help="repository root (default: the parent of tools/)")
    ap.add_argument("--check", action="store_true",
                    help="change nothing; exit 1 when the tree differs from a fresh run")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    try:
        want = expected(root)
    except SourceError as e:
        print(f"gen-agents: {e}", file=sys.stderr)
        return 2
    links = use_symlinks(root)
    diffs = []
    for path, target in LINKS:
        if not link_ok(root, path, target, links):
            diffs.append(path)
            if not a.check:
                write_link(root, path, target, links)
    for rel, text in sorted(want.items()):
        p = os.path.join(root, rel)
        cur = None
        if os.path.isfile(p) and not os.path.islink(p):
            with open(p, encoding="utf-8") as f:
                cur = f.read()
        if cur != text:
            diffs.append(rel)
            if not a.check:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                remove(p)
                with open(p, "w", encoding="utf-8") as f:
                    f.write(text)
    for rel in stale(root, want):
        diffs.append(rel)
        if not a.check:
            os.unlink(os.path.join(root, rel))
    if a.check:
        for d in diffs:
            print(f"gen-agents: out of date: {d}")
        if diffs:
            print("gen-agents: run tools/gen-agents.py (make agents) and commit the result", file=sys.stderr)
        return 1 if diffs else 0
    for d in diffs:
        print(f"gen-agents: wrote {d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
