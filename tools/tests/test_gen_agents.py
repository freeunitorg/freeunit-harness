"""Tests of tools/gen-agents.py and of the shared agent layout it maintains.

Each generator test works on a temporary copy of the sources. Nothing touches the network.

Run: python3 -m unittest discover -s tools/tests -v
"""
import os, posixpath, re, shutil, subprocess, sys, tempfile, unittest

sys.dont_write_bytecode = True
TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(TOOLS)
GEN = os.path.join(TOOLS, "gen-agents.py")
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")


def git(cwd, *args):
    subprocess.run(["git", "-C", cwd, *args], check=True, capture_output=True)


def md_links(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    for target in LINK_RE.findall(text):
        if re.match(r"[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith(("#", "/")):
            continue
        yield target.partition("#")[0]


class GenAgentsTest(unittest.TestCase):
    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix="gen-agents-test-"))
        self.addCleanup(shutil.rmtree, self.tmp)
        for d in ("agents", "recipes", "skills"):
            shutil.copytree(os.path.join(ROOT, d), os.path.join(self.tmp, d),
                            ignore=shutil.ignore_patterns("__pycache__"))
        shutil.copyfile(os.path.join(ROOT, "AGENTS.md"), os.path.join(self.tmp, "AGENTS.md"))
        git(self.tmp, "init", "-q")

    def gen(self, *args):
        return subprocess.run([sys.executable, GEN, "--root", self.tmp, *args], capture_output=True,
                              text=True, timeout=30, stdin=subprocess.DEVNULL)

    def p(self, rel):
        return os.path.join(self.tmp, rel)

    def test_generate_then_check_is_clean(self):
        self.assertEqual(self.gen("--check").returncode, 1)
        r = self.gen()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(os.readlink(self.p("CLAUDE.md")), "AGENTS.md")
        self.assertEqual(os.readlink(self.p(".agents/skills")), "../skills")
        self.assertEqual(os.readlink(self.p(".claude/skills")), "../skills")
        for f in ("perf-runner.md", "adversarial-reviewer.md"):
            for d in (".claude/agents", ".opencode/agents"):
                with open(self.p(f"{d}/{f}"), encoding="utf-8") as fh:
                    head = fh.read(300)
                self.assertTrue(head.startswith("---\n# Generated by tools/gen-agents.py from agents/"), head)
        self.assertTrue(os.path.isfile(self.p(".opencode/commands/perf-job.md")))
        r = self.gen("--check")
        self.assertEqual((r.returncode, r.stdout), (0, ""))

    def test_check_fails_on_an_edited_output_and_a_regenerate_fixes_it(self):
        self.gen()
        out = self.p(".claude/agents/perf-runner.md")
        with open(out, "a", encoding="utf-8") as f:
            f.write("hand edit\n")
        r = self.gen("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("out of date: .claude/agents/perf-runner.md", r.stdout)
        with open(out, encoding="utf-8") as f:
            self.assertIn("hand edit", f.read())  # --check changes nothing
        self.assertEqual(self.gen().returncode, 0)
        self.assertEqual(self.gen("--check").returncode, 0)

    def test_check_fails_on_a_source_edit_and_a_replaced_link(self):
        self.gen()
        with open(self.p("agents/ci-watcher.md"), "a", encoding="utf-8") as f:
            f.write("\nOne more rule.\n")
        os.unlink(self.p(".agents/skills"))
        os.symlink("../elsewhere", self.p(".agents/skills"))
        r = self.gen("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn(".claude/agents/ci-watcher.md", r.stdout)
        self.assertIn(".opencode/agents/ci-watcher.md", r.stdout)
        self.assertIn("out of date: .agents/skills", r.stdout)

    def test_stale_generated_file_is_removed_and_hand_written_file_is_kept(self):
        self.gen()
        os.unlink(self.p("recipes/perf-job.md"))
        with open(self.p(".opencode/commands/mine.md"), "w", encoding="utf-8") as f:
            f.write("---\ndescription: mine\n---\nhand written\n")
        r = self.gen("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn(".opencode/commands/perf-job.md", r.stdout)
        self.assertNotIn("mine.md", r.stdout)
        self.gen()
        self.assertFalse(os.path.exists(self.p(".opencode/commands/perf-job.md")))
        self.assertTrue(os.path.exists(self.p(".opencode/commands/mine.md")))

    def test_copies_instead_of_links_when_core_symlinks_is_false(self):
        git(self.tmp, "config", "core.symlinks", "false")
        r = self.gen()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertFalse(os.path.islink(self.p("CLAUDE.md")))
        with open(self.p("CLAUDE.md"), encoding="utf-8") as a, open(self.p("AGENTS.md"), encoding="utf-8") as b:
            self.assertEqual(a.read(), b.read())
        for d in (".agents/skills", ".claude/skills"):
            self.assertFalse(os.path.islink(self.p(d)))
            self.assertTrue(os.path.isfile(self.p(f"{d}/freeunit-build/SKILL.md")))
        self.assertEqual(self.gen("--check").returncode, 0)
        with open(self.p("skills/freeunit-build/SKILL.md"), "a", encoding="utf-8") as f:
            f.write("\nchanged\n")
        r = self.gen("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn(".agents/skills", r.stdout)
        self.assertIn(".claude/skills", r.stdout)
        self.assertEqual(self.gen().returncode, 0)
        self.assertEqual(self.gen("--check").returncode, 0)

    def test_bad_source_exits_2(self):
        with open(self.p("agents/broken.md"), "w", encoding="utf-8") as f:
            f.write("---\nname: broken\n---\nno description\n")
        r = self.gen()
        self.assertEqual(r.returncode, 2)
        self.assertIn("agents/broken.md: frontmatter has no description", r.stderr)
        with open(self.p("agents/broken.md"), "w", encoding="utf-8") as f:
            f.write("---\nname: other\ndescription: x\n---\nbody\n")
        r = self.gen()
        self.assertEqual(r.returncode, 2)
        self.assertIn("is not the file name", r.stderr)

    def test_generated_links_point_at_existing_files(self):
        self.gen()
        for d in (".claude/agents", ".opencode/agents", ".opencode/commands"):
            for f in os.listdir(self.p(d)):
                for target in md_links(self.p(f"{d}/{f}")):
                    path = posixpath.normpath(posixpath.join(d, target))
                    self.assertFalse(path.startswith(".."), f"{d}/{f}: {target}")
                    self.assertTrue(os.path.exists(os.path.join(ROOT, path)), f"{d}/{f}: {target}")


class LayoutTest(unittest.TestCase):
    """The checked-in tree."""

    def test_committed_outputs_are_up_to_date(self):
        r = subprocess.run([sys.executable, GEN, "--check"], capture_output=True, text=True, timeout=30)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_skill_names_match_directories(self):
        skills = os.path.join(ROOT, "skills")
        self.assertEqual([f for f in os.listdir(skills) if os.path.isfile(os.path.join(skills, f))], [],
                         "a file at the top of skills/ is read as a flat skill by some agents")
        for d in sorted(os.listdir(skills)):
            with open(os.path.join(skills, d, "SKILL.md"), encoding="utf-8") as f:
                m = re.match(r"---\nname: (\S+)\n", f.read())
            self.assertIsNotNone(m, d)
            self.assertEqual(m.group(1), d)
            self.assertTrue(d.startswith("freeunit-"), d)

    def test_skill_links_resolve_through_the_agent_paths(self):
        """Some agents resolve a link by text, not through the symlink, so .agents/skills/x/../../docs
        becomes .agents/docs. Every relative link inside skills/ must stay inside skills/."""
        for dirpath, _, files in os.walk(os.path.join(ROOT, "skills")):
            for f in files:
                if not f.endswith(".md"):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/")
                for target in md_links(os.path.join(ROOT, rel)):
                    for base in ("skills", ".agents/skills", ".claude/skills"):
                        here = posixpath.dirname(base + rel[len("skills"):])
                        path = posixpath.normpath(posixpath.join(here, target))
                        self.assertTrue(path.startswith(base + "/"), f"{rel}: {target} leaves {base}/")
                    real = posixpath.normpath(posixpath.join(posixpath.dirname(rel), target))
                    self.assertTrue(os.path.exists(os.path.join(ROOT, real)), f"{rel}: {target}")


if __name__ == "__main__":
    unittest.main()
