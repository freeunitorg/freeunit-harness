"""Tests of tools/relay, the GitHub issue channel between machines. Copyright (C) FreeUnit contributors.
A fake gh records each post; RELAY_COMMENTS gives the issue comments. Nothing touches the network.

Run: python3 -m unittest discover -s tools/tests -v
"""
import json, os, shutil, subprocess, sys, tempfile, unittest

sys.dont_write_bytecode = True
TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RELAY = os.path.join(TOOLS, "relay")
A, B = "a" * 40, "b" * 40
JOB = f"```job\nJOB=j1\nREV_A={A}\nREV_B={B}\nWORKLOAD=hello\nCONNS=6 32\nEXPECT=B within 2 percent\n```"


def c(cid, login, body, ts="2026-10-11T12:00:00Z"):
    return {"id": cid, "user": {"login": login}, "body": body, "created_at": ts, "html_url": f"https://x/{cid}"}


class RelayTest(unittest.TestCase):
    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix="relay-test-"))
        self.addCleanup(shutil.rmtree, self.tmp)
        self.posts = os.path.join(self.tmp, "posts")
        fake_gh = os.path.join(self.tmp, "gh")
        with open(fake_gh, "w") as f:   # records the body of each post; `gh api user` answers a login
            f.write(f'#!/bin/sh\nif [ "$2" = user ]; then echo \'{{"login":"me"}}\'; exit 0; fi\ncat >> {self.posts}\necho >> {self.posts}\n')
        self.perf = os.path.join(self.tmp, "perf-job.sh")
        with open(self.perf, "w") as f:  # the check passes; the run prints one PERF line, or exits with $FAKE_EXIT
            f.write('#!/bin/sh\n[ -n "$PERF_JOB_CHECK" ] && exit 0\necho "PERF j1 r1: NO CLAIM | report /none/compare.txt"\nexit ${FAKE_EXIT:-0}\n')
        os.chmod(fake_gh, 0o755); os.chmod(self.perf, 0o755)
        self.env = {k: v for k, v in os.environ.items() if not k.startswith(("RELAY_", "INBOX_", "PERF_"))}
        self.env.update(RELAY_GH=fake_gh, RELAY_PERF_JOB=self.perf, RELAY_DIR=os.path.join(self.tmp, "state"),
                        RELAY_COMMENTS=os.path.join(self.tmp, "c.json"), INBOX_LOG=os.path.join(self.tmp, "bus.log"),
                        RELAY_TRUSTED="andypost", RELAY_AGENT="laptop-perf")

    def comments(self, *cs):
        with open(self.env["RELAY_COMMENTS"], "w") as f: json.dump(list(cs), f)

    def relay(self, *args, env=None):
        return subprocess.run([sys.executable, RELAY, *args], capture_output=True, text=True,
                              env=dict(self.env, **(env or {})), cwd=self.tmp, stdin=subprocess.DEVNULL, timeout=20)

    def posted(self):
        if not os.path.exists(self.posts): return []
        with open(self.posts) as f: return [json.loads(l)["body"] for l in f if l.strip()]

    def test_usage_errors_exit_2(self):
        for args in ([], ["pull"], ["pull", "x"], ["bogus", "o/r#1"], ["post", "o/r#1"], ["post", "o/r#1", "hello"],
                     ["perf", "o/r#1", "--go"], ["state", "o/r#1", "x"]):
            r = self.relay(*args)
            self.assertEqual(r.returncode, 2, f"{args}: {r.stderr}")
            self.assertTrue(r.stderr.startswith("relay: "))
        self.assertEqual(self.posted(), [])

    def test_state_last_line_wins_and_done_closes(self):
        self.comments(c(1, "freeunit-agent[bot]", "text\nclaim: #585 — Hermes — hermes/585\n"),
                      c(2, "andypost", "claim: #647 -- Claude -- fix/x"),
                      c(3, "andypost", "takeover: #585 — Claude — no push in 24 h"),
                      c(4, "andypost", "done: #647 — https://github.com/o/r/pull/674 — 8 passed"))
        out = self.relay("state", "o/r#11").stdout
        self.assertRegex(out, r"held\s+#585\s+Claude \(andypost")
        self.assertRegex(out, r"done\s+#647\s+https://github.com/o/r/pull/674")

    def test_pull_copies_new_lines_once(self):
        self.comments(c(5, "freeunit-agent[bot]", "claim: #588 — Hermes — hermes/588"), c(6, "andypost", "no protocol here"))
        self.assertEqual(self.relay("pull", "o/r#11").returncode, 0)
        self.relay("pull", "o/r#11")
        with open(self.env["INBOX_LOG"]) as f: bus = f.read().splitlines()
        self.assertEqual(len(bus), 1)
        self.assertRegex(bus[0], r"^2026-10-11T12:00:00Z freeunit-agent\[bot\]@github claim [0-9a-f]{6} claim: #588 — Hermes — hermes/588 https://x/5$")

    def test_post_wraps_one_line_with_footer(self):
        self.assertEqual(self.relay("post", "o/r#11", "claim:", "#603", "—", "Claude", "—", "b").returncode, 0)
        self.assertEqual(self.posted(), ["claim: #603 — Claude — b\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"])

    def test_perf_lists_only_trusted_open_requests(self):
        self.comments(c(1, "stranger", "perf-request: j0 — x\n" + JOB),
                      c(2, "andypost", "perf-request: j1 — cloud\n" + JOB),
                      c(3, "andypost", "perf-request: j2 — cloud\n" + JOB),
                      c(4, "me", "perf-result: j2 — laptop — PERF ..."))
        out = self.relay("perf", "o/r#11").stdout
        self.assertIn("j1", out); self.assertNotIn("j0", out); self.assertNotIn("j2", out)

    def test_perf_run_claims_runs_and_posts_result(self):
        self.comments(c(2, "andypost", "perf-request: j1 — cloud\n" + JOB))
        r = self.relay("perf", "o/r#11", "--run")
        self.assertEqual(r.returncode, 0, r.stderr)
        posts = self.posted()
        self.assertTrue(posts[0].startswith("perf-claim: j1 — laptop-perf — lab"))
        self.assertTrue(posts[1].startswith("perf-result: j1 — laptop-perf — PERF j1 r1: NO CLAIM"))
        with open(os.path.join(self.env["RELAY_DIR"], "jobs", "j1.job")) as f: job = f.read()
        self.assertIn(f"REV_B={B}\n", job); self.assertIn("CONNS=6 32\n", job)

    def test_perf_busy_exits_75_and_says_so(self):
        self.comments(c(2, "andypost", "perf-request: j1 — cloud\n" + JOB))
        r = self.relay("perf", "o/r#11", "--run", env={"FAKE_EXIT": "75"})
        self.assertEqual(r.returncode, 75)
        self.assertIn("BUSY, nothing measured", self.posted()[1])

    def test_perf_refuses_unsafe_jobs_and_posts_nothing(self):
        bad = {"patch": f"JOB=j1\nREV_A={A}\nREV_B={B}\nPATCH_B=/etc/passwd\n",
               "configure": f"JOB=j1\nREV_A={A}\nREV_B={B}\nCONFIGURE_ARGS=--x\n",
               "short sha": f"JOB=j1\nREV_A=abc123\nREV_B={B}\n",
               "dollar": f"JOB=j1\nREV_A={A}\nREV_B={B}\nEXPECT=$(id)\n",
               "name": f"JOB=../j1\nREV_A={A}\nREV_B={B}\n",
               "mismatch": f"JOB=j9\nREV_A={A}\nREV_B={B}\n"}
        for why, body in bad.items():
            self.comments(c(2, "andypost", f"perf-request: j1 — cloud\n```job\n{body}```"))
            r = self.relay("perf", "o/r#11", "--run")
            self.assertEqual(r.returncode, 1, f"{why}: {r.stderr}")
        self.assertEqual(self.posted(), [])


if __name__ == "__main__":
    unittest.main()
